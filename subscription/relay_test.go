func TestRelaySubscriber_Process(t *testing.T) {
	tests := []struct {
		name              string
		relayMessages     []ws.WSMetadata
		batchSize         int16
		expectedCallCount int
		blockAt           int // index to block at, -1 if no block
		resumeAt          int // index to resume at, -1 if no resume
	}{
		{
			name:              "should process 5000 relays and persist with batch size 100",
			relayMessages:     generateRandomWSMetadata(5_000),
			batchSize:         1000,
			expectedCallCount: 5,
			blockAt:           -1,
			resumeAt:          -1,
		},
		{
			name:              "should process 12000 relays and persist with batch size 300",
			relayMessages:     generateRandomWSMetadata(12_000),
			batchSize:         3000,
			expectedCallCount: 4,
			blockAt:           -1,
			resumeAt:          -1,
		},
		{
			name:              "should block and then resume processing relays",
			relayMessages:     generateRandomWSMetadata(1_000),
			batchSize:         100,
			expectedCallCount: 10,
			blockAt:           300, // Block after 300 messages
			resumeAt:          700, // Resume after 700 messages
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := require.New(t)

			mockCache := newMockICache(t)
			blockCh := make(chan struct{})
			resumeCh := make(chan struct{})

			rs, err := NewRelaySubscriber(RelaySubscriberConfig{
				Cache:     mockCache,
				BatchSize: test.batchSize,
				BlockCh:   blockCh,
				ResumeCh:  resumeCh,
				Logger:    logger.New(),
			})
			c.NoError(err)

			relayCh := make(chan ws.WSMetadata, len(test.relayMessages))
			defer close(relayCh)

			rs.relayCh = relayCh

			// Split relayMessages into batches and generate expectedRelaysMap for each batch
			for i := 0; i < test.expectedCallCount; i++ {
				startIndex := i * int(test.batchSize)
				endIndex := startIndex + int(test.batchSize)
				if endIndex > len(test.relayMessages) {
					endIndex = len(test.relayMessages)
				}
				batch := test.relayMessages[startIndex:endIndex]
				expectedRelaysMap := generateExpectedRelaysMap(batch)

				// Expect SetWSRelays to be called with the expectedRelaysMap
				mockCache.On("SetWSRelays", expectedRelaysMap).Return(nil).Run(func(args mock.Arguments) {
					arg := args.Get(0).(map[cache.NodeKey]int64)
					c.Equal(expectedRelaysMap, arg)
				}).Once()
			}

			// Run Process in a goroutine to allow blocking and resuming
			go rs.Process(context.Background())

			for i, relay := range test.relayMessages {
				if i == test.blockAt {
					blockCh <- struct{}{}
				}
				if i == test.resumeAt {
					resumeCh <- struct{}{}
				}
				relayCh <- relay
			}

			// Wait for the Process to finish
			<-time.After(2 * time.Second)

			// Check if the expected number of calls to SetWSRelays matches
			mockCache.AssertNumberOfCalls(t, "SetWSRelays", test.expectedCallCount)
			mockCache.AssertExpectations(t)
		})
	}
}

func generateRandomWSMetadata(n int) []ws.WSMetadata {
	nodes := make([]node.V0Node, 5)
	for i := range nodes {
		nodes[i] = node.V0Node{
			ProviderNode: provider.Node{PublicKey: fmt.Sprintf("node_%d", i)},
		}
	}

	chains := make([]types.RelayChainID, 10)
	for i := range chains {
		chains[i] = types.RelayChainID(fmt.Sprintf("chain_%d", i))
	}

	apps := make([]types.PortalAppLite, 8)
	for i := range apps {
		apps[i] = types.PortalAppLite{ID: types.PortalAppID(fmt.Sprintf("app_%d", i))}
	}

	metadata := make([]ws.WSMetadata, n)
	for i := 0; i < n; i++ {
		metadata[i] = ws.WSMetadata{
			NodeID:      nodes[rand.Intn(len(nodes))].ID(),
			ChainID:     chains[rand.Intn(len(chains))],
			PortalAppID: apps[rand.Intn(len(apps))].ID,
		}
	}

	return metadata
}

func generateExpectedRelaysMap(relays []ws.WSMetadata) map[cache.NodeKey]int64 {
	expectedRelaysMap := make(map[cache.NodeKey]int64)
	for _, relay := range relays {
		key := cache.NodeKey{
			NodeID:      relay.NodeID,
			ChainID:     relay.ChainID,
			PortalAppID: relay.PortalAppID,
		}
		expectedRelaysMap[key]++
	}
	return expectedRelaysMap
}

